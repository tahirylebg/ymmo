def point(latitude: float, longitude: float) -> tuple[float, float]:
    """SVG coordinates (viewBox 0 0 WIDTH HEIGHT) of a latitude / longitude."""
    x = (longitude - LON_MIN) * _K * _SCALE
    y = (LAT_MAX - latitude) * _SCALE
    return round(x, 1), round(y, 1)
